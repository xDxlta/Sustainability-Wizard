/* Writes crm/data/data.js from crm/data/hotels_public.json and crm/data/cases_public.json.
 * The pipeline tool loads data.js with a <script> tag, so it also works when opened from a folder
 * (file://), where a browser does not allow reading JSON files. The JSON files stay the source:
 * edit them, then run  node tools/build-crm-data.js  (npm run build:crm). A test checks they agree.
 * The confidential projects file is never read here. */
const fs = require('fs'), path = require('path');
const dir = path.resolve(__dirname, '..', 'crm', 'data');

function build() {
  const hotels = JSON.parse(fs.readFileSync(path.join(dir, 'hotels_public.json'), 'utf8'));
  const cases = JSON.parse(fs.readFileSync(path.join(dir, 'cases_public.json'), 'utf8'));
  return '/* Generated by tools/build-crm-data.js from hotels_public.json and cases_public.json. Do not edit. */\n' +
    'window.CRM_DATA = ' + JSON.stringify({ hotels: hotels, cases: cases }) + ';\n';
}

if (require.main === module) {
  const out = path.join(dir, 'data.js');
  fs.writeFileSync(out, build());
  console.log('wrote', path.relative(process.cwd(), out), (fs.statSync(out).size / 1024).toFixed(0) + ' kB');
}
module.exports = { build };
